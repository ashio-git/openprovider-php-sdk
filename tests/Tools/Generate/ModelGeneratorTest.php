    /**
     * One GET operation per `data` shape: a listing (results of models and an integer total) and
     * three near misses.
     *
     * @return array<string, mixed>
     */
    private static function listingSpec(): array
    {
        $ref = static fn (string $name): array => ['$ref' => '#/definitions/' . $name];
        $owners = ['type' => 'array', 'items' => $ref('domain.domainOwner')];
        $data = [
            'ListThings' => ['results' => $owners, 'total' => ['type' => 'integer', 'format' => 'int32']],
            'Names' => ['results' => ['type' => 'array', 'items' => ['type' => 'string']], 'total' => ['type' => 'integer']],
            'Check' => ['results' => $owners],
            'Odd' => ['results' => $owners, 'total' => ['type' => 'string']],
        ];
        $paths = [];
        $definitions = ['domain.domainOwner' => ['type' => 'object']];
        foreach ($data as $name => $properties) {
            $paths['/' . strtolower($name)] = ['get' => [
                'operationId' => $name,
                'responses' => ['200' => ['schema' => $ref("domain.domain{$name}Response")]],
            ]];
            $definitions["domain.domain{$name}Response"] = ['type' => 'object', 'properties' => ['code' => ['type' => 'integer'], 'data' => $ref("domain.domain{$name}ResponseData")]];
            $definitions["domain.domain{$name}ResponseData"] = ['type' => 'object', 'properties' => $properties];
        }

        return ['paths' => $paths, 'definitions' => $definitions];
    }

    /**
     * @param array<array-key, mixed> $spec
     */
    private static function json(array $spec): string
    {
        return json_encode($spec, JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES);
    }
