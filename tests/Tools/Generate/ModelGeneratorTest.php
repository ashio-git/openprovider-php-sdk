    /**
     * @param array<string, mixed> $schema
     */
    #[DataProvider('unsupported')]
    public function testASchemaTheGeneratorCannotTypeIsRefusedWithItsLocation(array $schema, string $message): void
    {
        $spec = ArrayPath::with(self::spec(), $schema, 'definitions', 'domain.domainThing', 'properties', 'odd');
        $spec = ArrayPath::with($spec, ['type' => 'string'], 'definitions', 'domain.domainPlain');

        try {
            ModelGenerator::generate(self::json($spec));
            self::fail('The schema was accepted');
        } catch (SpecException $e) {
            self::assertStringContainsString('domain.domainThing.odd', $e->getMessage());
            self::assertStringContainsString($message, $e->getMessage());
        }
    }

    public function testInvalidJsonIsRefused(): void
    {
        $this->expectException(SpecException::class);

        ModelGenerator::generate('{');
    }

