final class ModelGeneratorTest extends TestCase
{
    public function testItWritesOneFilePerReachableDefinitionPlusTheMap(): void
    {
        $files = ModelGenerator::generate(self::json(self::spec()));

        self::assertSame(['Domain/DomainOwner.php', 'Domain/DomainSize.php', 'Domain/DomainThing.php', 'ModelMap.php'], array_keys($files));
    }

    public function testAModelHasEveryFieldKindTypedAndDocumented(): void
    {
        $expected = <<<'PHP'
            <?php

            declare(strict_types=1);

            namespace Ashio\OpenProvider\Model\Domain;

            use Ashio\OpenProvider\Serialization\Fields;
            use Ashio\OpenProvider\Serialization\Model;

            /**
             * A thing
             *
             * Line one.
             * Line two * / ends.
             *
             * \@notatag
             *
             * Spec definition `domain.domainThing`.
             *
             * @experimental Documented only by the developer portal (https://portal.example/spec.js); it may change without notice.
             *
             * @generated by `php tools/generate models` from spec/openprovider.json. Do not edit.
             */
            final readonly class DomainThing implements Model
            {
                /**
                 * @param int|null $id Thing ID
                 * @param string|null $name Name of the thing
                 * @param int|float|null $price
                 * @param bool|null $isActive Active (`is_active`, API default: false)
                 * @param string|null $size (one of DomainSize::VALUES)
                 * @param DomainOwner|null $owner Owner
                 * @param list<string>|null $tags
                 * @param list<int>|null $counts
                 * @param list<DomainOwner>|null $owners
                 * @param list<string>|null $sizes (one of DomainSize::VALUES)
                 * @param array<array-key, bool>|null $skuValues SKU values (`sku_values`)
                 * @param array<array-key, mixed> $extra What the typed properties cannot hold, exactly as received: undeclared keys, explicit nulls and values of another type.
                 */
                public function __construct(
                    public ?int $id = null,
                    public ?string $name = null,
                    public int|float|null $price = null,
                    public ?bool $isActive = null,
                    public ?string $size = null,
                    public ?DomainOwner $owner = null,
                    public ?array $tags = null,
                    public ?array $counts = null,
                    public ?array $owners = null,
                    public ?array $sizes = null,
                    public ?array $skuValues = null,
                    public array $extra = [],
                ) {
                }

                /**
                 * Tolerant: a value of another type than the spec declares is kept in $extra, never refused.
                 *
                 * @param array<array-key, mixed> $data
                 */
                #[\Override]
                public static function fromArray(array $data): static
                {
                    // Arguments run in order: each Fields call takes its key out of $data when the value
                    // has the declared type, so what is left at the end is $extra.
                    return new self(
                        id: Fields::int($data, 'id'),
                        name: Fields::string($data, 'name'),
                        price: Fields::number($data, 'price'),
                        isActive: Fields::bool($data, 'is_active'),
                        size: Fields::string($data, 'size'),
                        owner: Fields::object($data, 'owner', DomainOwner::class),
                        tags: Fields::strings($data, 'tags'),
                        counts: Fields::ints($data, 'counts'),
                        owners: Fields::objects($data, 'owners', DomainOwner::class),
                        sizes: Fields::strings($data, 'sizes'),
                        skuValues: Fields::boolMap($data, 'sku_values'),
                        extra: $data,
                    );
                }

                /**
                 * @return array<array-key, mixed>
                 */
                #[\Override]
                public function toArray(): array
                {
                    return Fields::toArray($this->fields(), $this->extra);
                }

                #[\Override]
                public function jsonSerialize(): \stdClass
                {
                    return Fields::toJson($this->fields(), $this->extra, ['sku_values']);
                }

                /**
                 * @return array<string, mixed>
                 */
                private function fields(): array
                {
                    return [
                        'id' => $this->id,
                        'name' => $this->name,
                        'price' => $this->price,
                        'is_active' => $this->isActive,
                        'size' => $this->size,
                        'owner' => $this->owner,
                        'tags' => $this->tags,
                        'counts' => $this->counts,
                        'owners' => $this->owners,
                        'sizes' => $this->sizes,
                        'sku_values' => $this->skuValues,
                    ];
                }
            }

            PHP;

        self::assertSame($expected, ModelGenerator::generate(self::json(self::spec()))['Domain/DomainThing.php']);
    }

    public function testAModelWithoutPropertiesOnlyCarriesExtra(): void
    {
        $source = ModelGenerator::generate(self::json(self::spec()))['Domain/DomainOwner.php'];

        self::assertStringContainsString("    public function __construct(\n        public array \$extra = [],\n    ) {", $source);
        self::assertStringContainsString("        return new self(\n            extra: \$data,\n        );", $source);
        self::assertStringContainsString("        return Fields::toJson(\$this->fields(), \$this->extra);\n", $source);
        self::assertStringContainsString("    private function fields(): array\n    {\n        return [];\n    }", $source);
        self::assertStringNotContainsString('@experimental', $source);
    }

    public function testAModelWithResultsOfModelsAndAnIntegerTotalIsAListing(): void
    {
        $source = ModelGenerator::generate(self::json(self::listingSpec()))['Domain/DomainListThingsResponseData.php'];

        self::assertStringContainsString("use Ashio\\OpenProvider\\Pagination\\Listing;\nuse Ashio\\OpenProvider\\Serialization\\Fields;\n\n", $source);
        self::assertStringNotContainsString('use Ashio\\OpenProvider\\Serialization\\Model;', $source, 'Listing extends Model; importing both leaves an unused import');
        self::assertStringContainsString(" * @generated by `php tools/generate models` from spec/openprovider.json. Do not edit.\n *\n * @implements Listing<DomainOwner>\n */\nfinal readonly class DomainListThingsResponseData implements Listing\n", $source);
        self::assertStringContainsString(<<<'PHP'
                /**
                 * This page's items; a page without `results` is empty.
                 *
                 * @return list<DomainOwner>
                 */
                #[\Override]
                public function items(): array
                {
                    return $this->results ?? [];
                }

                /**
                 * The number of items across all pages, or null when the API does not send it.
                 */
                #[\Override]
                public function total(): ?int
                {
                    return $this->total;
                }

                /**
                 * @return array<string, mixed>
                 */
                private function fields(): array
            PHP, $source);
    }

    /**
     * @return iterable<string, array{string}>
     */
    public static function notListings(): iterable
    {
        yield 'results of strings' => ['Domain/DomainNamesResponseData.php'];
        yield 'no total' => ['Domain/DomainCheckResponseData.php'];
        yield 'a total that is not an integer' => ['Domain/DomainOddResponseData.php'];
    }

    #[DataProvider('notListings')]
    public function testAnyOtherModelIsNotAListing(string $file): void
    {
        $source = ModelGenerator::generate(self::json(self::listingSpec()))[$file];

        self::assertStringContainsString(' implements Model' . "\n", $source);
        self::assertStringNotContainsString('Listing', $source);
        self::assertStringNotContainsString('function items()', $source);
    }

    public function testAnEnumIsAClassOfStringConstants(): void
    {
        $expected = <<<'PHP'
            <?php

            declare(strict_types=1);

            namespace Ashio\OpenProvider\Model\Domain;

            /**
             * Size
             *
             * Values of the spec definition `domain.domainSize`. Properties that hold one are typed string, so a
             * value the API adds later still reads.
             *
             * @generated by `php tools/generate models` from spec/openprovider.json. Do not edit.
             */
            final class DomainSize
            {
                public const S = 'S';
                public const X_LARGE = 'x-large';

                /** @var list<string> */
                public const VALUES = [
                    self::S,
                    self::X_LARGE,
                ];

                private function __construct()
                {
                }
            }

            PHP;

        self::assertSame($expected, ModelGenerator::generate(self::json(self::spec()))['Domain/DomainSize.php']);
    }

    public function testTheMapListsEveryGeneratedClassByDefinition(): void
    {
        $map = ModelGenerator::generate(self::json(self::spec()))['ModelMap.php'];

        self::assertStringContainsString("    public const MODELS = [\n        'domain.domainOwner' => Domain\\DomainOwner::class,\n        'domain.domainThing' => Domain\\DomainThing::class,\n    ];", $map);
        self::assertStringContainsString("    public const ENUMS = [\n        'domain.domainSize' => Domain\\DomainSize::class,\n    ];", $map);
        self::assertStringContainsString('@generated', $map);
    }

    public function testTheOutputDependsOnlyOnTheSpec(): void
    {
        $json = self::json(self::spec());

        self::assertSame(ModelGenerator::generate($json), ModelGenerator::generate($json));
    }

