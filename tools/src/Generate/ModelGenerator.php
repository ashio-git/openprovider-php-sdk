<?php

declare(strict_types=1);

namespace Ashio\OpenProvider\Tools\Generate;

use Ashio\OpenProvider\Tools\Spec\Json;
use Ashio\OpenProvider\Tools\Spec\SpecException;

/**
 * Writes src/Model from spec/openprovider.json: an immutable model per reachable object
 * definition (plan A7), a class of constants per reachable string enum, and ModelMap.
 *
 * The output is a pure function of the spec: same spec, same bytes.
 */
final class ModelGenerator
{
    public const MARKER = '@generated by `php tools/generate models`';
    private const GENERATED = ' * ' . self::MARKER . ' from spec/openprovider.json. Do not edit.';
    private const EXTRA_DOC = 'What the typed properties cannot hold, exactly as received: undeclared keys, explicit nulls and values of another type.';

    /**
     * @return array<string, string> path relative to src/Model => source, sorted by path
     */
    public static function generate(string $specJson): array
    {
        try {
            $spec = json_decode($specJson, true, 512, JSON_THROW_ON_ERROR);
        } catch (\JsonException $e) {
            throw new SpecException('spec/openprovider.json is not valid JSON: ' . $e->getMessage(), 0, $e);
        }
        $spec = Json::object($spec, 'spec/openprovider.json');
        $definitions = Json::object($spec['definitions'] ?? null, 'definitions');
        $set = ModelSet::fromSpec($spec);
        $classes = NameMap::classes([...$set->models, ...$set->enums]);
        $portal = DocText::portalUrl($spec);

        $files = [];
        foreach ($set->models as $name) {
            $files[NameMap::path($classes[$name])] = self::model($name, Json::object($definitions[$name], $name), $definitions, $classes, $portal);
        }
        if ($set->unsupported !== []) {
            throw new SpecException(sprintf('%s: reachable, but neither an object nor a string enum', implode(', ', $set->unsupported)));
        }
        foreach ($set->enums as $name) {
            $files[NameMap::path($classes[$name])] = self::enum($name, Json::object($definitions[$name], $name), $classes[$name], $portal);
        }
        $files['ModelMap.php'] = self::map($set, $classes);
        ksort($files, SORT_STRING);

        return $files;
    }

    /**
     * @param array<array-key, mixed> $definition
     * @param array<array-key, mixed> $definitions
     * @param array<string, string>   $classes
     */
    private static function model(string $name, array $definition, array $definitions, array $classes, ?string $portal): string
    {
        [$namespace, $short] = self::split($classes[$name]);
        $schemas = Json::object($definition['properties'] ?? [], "$name properties");
        $properties = NameMap::properties($name, array_map('strval', array_keys($schemas)));

        $params = [];
        $promoted = [];
        $readers = [];
        $fields = [];
        $maps = [];
        foreach ($properties as $key => $property) {
            $schema = Json::object($schemas[$key], "$name.$key");
            $type = FieldType::resolve($schema, $definitions, $classes, "$name.$key");
            $params[] = rtrim(sprintf('     * @param %s $%s %s', $type->docType($namespace), $property, self::fieldDoc($key, $property, $schema, $type, $namespace)));
            $promoted[] = sprintf('        public %s $%s = null,', $type->phpType($namespace), $property);
            $readers[] = sprintf('            %s: %s,', $property, $type->reader($key, $namespace));
            $fields[] = sprintf('            %s => $this->%s,', var_export($key, true), $property);
            if ($type->container === 'map') {
                $maps[] = var_export($key, true);
            }
        }

        $lines = [
            '<?php',
            '',
            'declare(strict_types=1);',
            '',
            "namespace $namespace;",
            '',
            'use Ashio\OpenProvider\Serialization\Fields;',
            'use Ashio\OpenProvider\Serialization\Model;',
            '',
            ...self::classDoc($definition, ["Spec definition `$name`."], $portal),
            "final readonly class $short implements Model",
            '{',
            '    /**',
            ...$params,
            '     * @param array<array-key, mixed> $extra ' . self::EXTRA_DOC,
            '     */',
            '    public function __construct(',
            ...$promoted,
            '        public array $extra = [],',
            '    ) {',
            '    }',
            '',
            '    /**',
            '     * Tolerant: a value of another type than the spec declares is kept in $extra, never refused.',
            '     *',
            '     * @param array<array-key, mixed> $data',
            '     */',
            '    #[\Override]',
            '    public static function fromArray(array $data): static',
            '    {',
            ...($readers === [] ? [] : [
                '        // Arguments run in order: each Fields call takes its key out of $data when the value',
                '        // has the declared type, so what is left at the end is $extra.',
            ]),
            '        return new self(',
            ...$readers,
            '            extra: $data,',
            '        );',
            '    }',
            '',
            '    /**',
            '     * @return array<array-key, mixed>',
            '     */',
            '    #[\Override]',
            '    public function toArray(): array',
            '    {',
            '        return Fields::toArray($this->fields(), $this->extra);',
            '    }',
            '',
            '    #[\Override]',
            '    public function jsonSerialize(): \stdClass',
            '    {',
            '        return Fields::toJson($this->fields(), $this->extra' . ($maps === [] ? '' : ', [' . implode(', ', $maps) . ']') . ');',
            '    }',
            '',
            '    /**',
            '     * @return array<string, mixed>',
            '     */',
            '    private function fields(): array',
            '    {',
            ...($fields === [] ? ['        return [];'] : ['        return [', ...$fields, '        ];']),
            '    }',
            '}',
        ];

        return implode("\n", $lines) . "\n";
    }

    /**
     * @param array<array-key, mixed> $definition
     */
    private static function enum(string $name, array $definition, string $class, ?string $portal): string
    {
        [$namespace, $short] = self::split($class);
        $values = [];
        foreach (Json::list($definition['enum'], "$name enum") as $value) {
            $values[] = Json::string($value, "$name enum value");
        }
        $constants = NameMap::constants($name, $values);

        $lines = [
            '<?php',
            '',
            'declare(strict_types=1);',
            '',
            "namespace $namespace;",
            '',
            ...self::classDoc($definition, [
                "Values of the spec definition `$name`. Properties that hold one are typed string, so a",
                'value the API adds later still reads.',
            ], $portal),
            "final class $short",
            '{',
            ...array_map(static fn (string $value, string $constant): string => sprintf('    public const %s = %s;', $constant, var_export($value, true)), array_keys($constants), $constants),
            '',
            '    /** @var list<string> */',
            '    public const VALUES = [',
            ...array_map(static fn (string $constant): string => "        self::$constant,", array_values($constants)),
            '    ];',
            '',
            '    private function __construct()',
            '    {',
            '    }',
            '}',
        ];

        return implode("\n", $lines) . "\n";
    }

    /**
     * @param array<string, string> $classes
     */
    private static function map(ModelSet $set, array $classes): string
    {
        $lines = [
            '<?php',
            '',
            'declare(strict_types=1);',
            '',
            'namespace ' . NameMap::NAMESPACE . ';',
            '',
            'use Ashio\OpenProvider\Serialization\Model;',
            '',
            '/**',
            sprintf(' * The class of every definition generated from spec/openprovider.json: %d models and %d enums.', count($set->models), count($set->enums)),
            ' *',
            ' * The definitions that are not here are read by the client core: the success envelopes',
            ' * (Response\ApiResponse), the error schemas (Exception\ApiException) and their warnings',
            ' * (Response\Warning).',
            ' *',
            self::GENERATED,
            ' */',
            'final class ModelMap',
            '{',
            '    /** @var array<string, class-string<Model>> */',
            ...self::mapConstant('MODELS', $set->models, $classes),
            '',
            '    /** @var array<string, class-string> */',
            ...self::mapConstant('ENUMS', $set->enums, $classes),
            '',
            '    private function __construct()',
            '    {',
            '    }',
            '}',
        ];

        return implode("\n", $lines) . "\n";
    }

    /**
     * @param list<string>          $names
     * @param array<string, string> $classes
     *
     * @return list<string>
     */
    private static function mapConstant(string $constant, array $names, array $classes): array
    {
        if ($names === []) {
            return ["    public const $constant = [];"];
        }
        $lines = ["    public const $constant = ["];
        foreach ($names as $name) {
            $lines[] = sprintf('        %s => %s::class,', var_export($name, true), substr($classes[$name], strlen(NameMap::NAMESPACE) + 1));
        }
        $lines[] = '    ];';

        return $lines;
    }

    /**
     * Title, description, the given note, @experimental when the portal is the only source, and
     * the @generated marker.
     *
     * @param array<array-key, mixed> $definition
     * @param list<string>            $note
     *
     * @return list<string>
     */
    private static function classDoc(array $definition, array $note, ?string $portal): array
    {
        $title = is_string($definition['title'] ?? null) ? $definition['title'] : '';
        $description = is_string($definition['description'] ?? null) ? $definition['description'] : '';
        $sections = [];
        foreach ([$title, $description === $title ? '' : $description] as $text) {
            if (trim($text) !== '') {
                $sections[] = DocText::lines($text);
            }
        }
        $sections[] = $note;
        if (($definition['x-experimental'] ?? false) === true) {
            $sections[] = [DocText::experimental($portal)];
        }

        $lines = ['/**'];
        foreach ($sections as $i => $section) {
            if ($i > 0) {
                $lines[] = ' *';
            }
            foreach ($section as $line) {
                $lines[] = $line === '' ? ' *' : ' * ' . $line;
            }
        }
        $lines[] = ' *';
        $lines[] = self::GENERATED;
        $lines[] = ' */';

        return $lines;
    }

    /**
     * @param array<array-key, mixed> $schema
     */
    private static function fieldDoc(string $key, string $property, array $schema, FieldType $type, string $namespace): string
    {
        $text = is_string($schema['title'] ?? null) && trim($schema['title']) !== ''
            ? $schema['title']
            : (is_string($schema['description'] ?? null) ? $schema['description'] : '');
        $notes = [];
        if ($key !== $property) {
            $notes[] = "`$key`";
        }
        if ($type->enum !== null) {
            $notes[] = 'one of ' . FieldType::reference($type->enum, $namespace) . '::VALUES';
        }
        if (array_key_exists('default', $schema)) {
            $notes[] = 'API default: ' . (string) json_encode($schema['default'], JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
        }
        $text = DocText::inline($text);

        return trim($text . ($notes === [] ? '' : ' (' . implode(', ', $notes) . ')'));
    }

    /**
     * @return array{string, string} namespace and short name
     */
    private static function split(string $class): array
    {
        $at = (int) strrpos($class, '\\');

        return [substr($class, 0, $at), substr($class, $at + 1)];
    }
}
