<?php

declare(strict_types=1);

namespace Ashio\OpenProvider\Tools\Generate;

use Ashio\OpenProvider\Tools\Spec\Json;
use Ashio\OpenProvider\Tools\Spec\SpecException;

/**
 * Writes src/Exception/ErrorCatalog.php from spec/error-codes.json (descriptions and
 * resolutions) and spec/behavior.json (errorClasses).
 */
final class ErrorCatalogGenerator
{
    private const CLASSES = [
        'authentication' => 'Authentication',
        'rateLimited' => 'RateLimited',
        'maintenance' => 'Maintenance',
        'notFound' => 'NotFound',
        'validation' => 'Validation',
    ];

    public static function generate(string $errorCodesJson, string $behaviorJson): string
    {
        $codes = Json::object(Json::object(Json::decode($errorCodesJson, 'error-codes.json'), 'error-codes.json')['codes'] ?? null, 'codes');
        $descriptions = [];
        $resolutions = [];
        foreach ($codes as $code => $entry) {
            if (!is_int($code)) {
                throw new SpecException(sprintf('error-codes.json: "%s" is not a numeric code', $code));
            }
            $entry = Json::object($entry, "code $code");
            $descriptions[$code] = Json::string($entry['description'] ?? null, "code $code description");
            if (isset($entry['resolution'])) {
                $resolutions[$code] = Json::string($entry['resolution'], "code $code resolution");
            }
        }
        ksort($descriptions);
        ksort($resolutions);

        $behavior = Json::object(Json::decode($behaviorJson, 'behavior.json'), 'behavior.json');
        $categories = [];
        foreach (Json::object($behavior['errorClasses'] ?? null, 'errorClasses') as $class => $definition) {
            if ($class === '$comment') {
                continue;
            }
            $case = self::CLASSES[$class] ?? throw new SpecException(sprintf('errorClasses.%s is not a known class', $class));
            foreach (Json::list(Json::object($definition, (string) $class)['codes'] ?? null, "$class codes") as $code) {
                if (!is_int($code)) {
                    throw new SpecException(sprintf('errorClasses.%s lists a non-integer code', $class));
                }
                if (!isset($descriptions[$code])) {
                    throw new SpecException(sprintf('errorClasses.%s lists %d, which error-codes.json does not have', $class, $code));
                }
                if (isset($categories[$code])) {
                    throw new SpecException(sprintf('Code %d is in both %s and %s', $code, $categories[$code], $case));
                }
                $categories[$code] = $case;
            }
        }
        ksort($categories);

        $lines = [
            '<?php',
            '',
            'declare(strict_types=1);',
            '',
            'namespace Ashio\OpenProvider\Exception;',
            '',
            '/**',
            sprintf(' * The %d API error codes of the Openprovider knowledge base and their classification.', count($descriptions)),
            ' *',
            ' * @generated by `php tools/generate errors` from spec/error-codes.json and spec/behavior.json. Do not edit.',
            ' */',
            'final class ErrorCatalog',
            '{',
            '    /** @var array<int, string> */',
            '    private const DESCRIPTIONS = [',
            ...self::entries($descriptions),
            '    ];',
            '',
            '    /** @var array<int, string> */',
            '    private const RESOLUTIONS = [',
            ...self::entries($resolutions),
            '    ];',
            '',
            '    /** @var array<int, ErrorCategory> */',
            '    private const CATEGORIES = [',
            ...array_map(static fn (int $code, string $case): string => "        $code => ErrorCategory::$case,", array_keys($categories), $categories),
            '    ];',
            '',
            '    public static function describe(int $code): ?string',
            '    {',
            '        return self::DESCRIPTIONS[$code] ?? null;',
            '    }',
            '',
            '    public static function resolution(int $code): ?string',
            '    {',
            '        return self::RESOLUTIONS[$code] ?? null;',
            '    }',
            '',
            '    public static function category(int $code): ErrorCategory',
            '    {',
            '        return self::CATEGORIES[$code] ?? ErrorCategory::Other;',
            '    }',
            '',
            '    public static function count(): int',
            '    {',
            '        return count(self::DESCRIPTIONS);',
            '    }',
            '}',
        ];

        return implode("\n", $lines) . "\n";
    }

    /**
     * @param array<int, string> $map
     *
     * @return list<string>
     */
    private static function entries(array $map): array
    {
        $lines = [];
        foreach ($map as $code => $text) {
            $lines[] = sprintf('        %d => %s,', $code, var_export($text, true));
        }

        return $lines;
    }
}
