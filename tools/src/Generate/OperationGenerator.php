<?php

declare(strict_types=1);

namespace Ashio\OpenProvider\Tools\Generate;

use Ashio\OpenProvider\Tools\Spec\Json;
use Ashio\OpenProvider\Tools\Spec\SpecException;

/**
 * Writes the operation layer from spec/openprovider.json (plan A8):
 *
 * - `Service/<Group>Service.php`: one service per tag group of `x-tagGroups`, with one method
 *   per operation carrying its #[Operation];
 * - `Service/Operations.php`: the registry of parameter specs the request encoder reads;
 * - `OpenProvider.php`: the facade, one accessor per service.
 *
 * Paths are relative to src/. The output is a pure function of the spec and spec/behavior.json:
 * same inputs, same bytes.
 */
final class OperationGenerator
{
    public const MARKER = '@generated by `php tools/generate operations`';
    public const NAMESPACE = 'Ashio\OpenProvider\Service';

    /**
     * Tag groups left for a later step, with the reason. Their operations get no method yet; the
     * registry test and the conformance audit report them as pending, not as missing. None today.
     *
     * @var array<string, string>
     */
    public const DEFERRED_GROUPS = [];

    private const GENERATED = ' * ' . self::MARKER . ' from spec/openprovider.json. Do not edit.';
    private const HTTP_METHODS = ['get', 'post', 'put', 'delete', 'patch'];
    private const BASE_CLASS = 'Ashio\OpenProvider\Client\AbstractService';
    private const ALWAYS_IMPORTED = [
        self::BASE_CLASS,
        'Ashio\OpenProvider\Exception\OpenProviderException',
        'Ashio\OpenProvider\Response\ApiResponse',
        'Ashio\OpenProvider\Spec\Operation',
    ];

    /** The methods of AbstractService, which no operation can take. */
    private const RESERVED_METHODS = ['call', 'object', 'objects'];

    private const MAX_LINE = 120;

    /**
     * @param array<string, string> $deferred tag group => why its operations get no method yet
     *
     * @return array<string, string> path relative to src => source, sorted by path
     */
    public static function generate(string $specJson, string $behaviorJson, array $deferred = self::DEFERRED_GROUPS): array
    {
        $spec = Json::object(self::decode($specJson, 'spec/openprovider.json'), 'spec/openprovider.json');
        $public = self::publicOperations(Json::object(self::decode($behaviorJson, 'spec/behavior.json'), 'spec/behavior.json'));
        $definitions = Json::object($spec['definitions'] ?? null, 'definitions');
        $set = ModelSet::fromSpec($spec);
        $classes = NameMap::classes([...$set->models, ...$set->enums]);
        $portal = DocText::portalUrl($spec);
        [$groupOf, $groupTags] = self::groups($spec);

        $byGroup = [];
        $all = [];
        foreach (Json::object($spec['paths'] ?? null, 'paths') as $path => $item) {
            foreach (Json::object($item, "paths.$path") as $method => $operation) {
                if (!in_array($method, self::HTTP_METHODS, true)) {
                    continue;
                }
                $operation = Json::object($operation, "$method $path");
                $entry = self::operation((string) $method, (string) $path, $operation, $groupOf, $public, $classes, $definitions);
                if (isset($deferred[$entry['group']])) {
                    continue;
                }
                $byGroup[$entry['group']][] = $entry;
                $all[] = $entry;
            }
        }

        $files = [];
        $services = [];
        foreach (array_keys($groupTags) as $group) {
            if (!isset($byGroup[$group])) {
                continue;
            }
            $class = self::serviceClass($group);
            $services[$group] = $class;
            $files['Service/' . $class . '.php'] = self::service($group, $class, $groupTags[$group], $byGroup[$group], $portal);
        }
        $files['Service/Operations.php'] = self::registry($all);
        $files['OpenProvider.php'] = self::facade($services, $groupTags);
        ksort($files, SORT_STRING);

        return $files;
    }

    /**
     * The service class of a tag group: its words, capitalised, then `Service`
     * (`Reseller/Customer` → `ResellerCustomerService`, `DNS` → `DnsService`).
     */
    public static function serviceClass(string $group): string
    {
        $name = '';
        foreach (preg_split('/[^A-Za-z0-9]+/', $group, -1, PREG_SPLIT_NO_EMPTY) ?: [] as $word) {
            $name .= ucfirst(strtoupper($word) === $word ? strtolower($word) : $word);
        }
        if (preg_match('/^[A-Z][A-Za-z0-9]*$/', $name) !== 1) {
            throw new SpecException(sprintf('The tag group "%s" does not make a class name', $group));
        }

        return $name . 'Service';
    }

    /**
     * The method of an operation: its operationId in camelCase, without the `Mixin<n>` suffix
     * gRPC-gateway leaves on some of them (`DeleteDomainMixin8` → `deleteDomain`).
     */
    public static function methodName(string $operationId): string
    {
        $name = lcfirst((string) preg_replace('/Mixin\d+$/', '', $operationId));
        if (preg_match('/^[a-z][A-Za-z0-9]*$/', $name) !== 1) {
            throw new SpecException(sprintf('%s: "%s" is not a valid method name', $operationId, $name));
        }
        if (in_array(strtolower($name), self::RESERVED_METHODS, true) || str_starts_with($name, '__')) {
            throw new SpecException(sprintf('%s: the method name %s() is reserved', $operationId, $name));
        }

        return $name;
    }

    private static function decode(string $json, string $origin): mixed
    {
        try {
            return json_decode($json, true, 512, JSON_THROW_ON_ERROR);
        } catch (\JsonException $e) {
            throw new SpecException(sprintf('%s is not valid JSON: %s', $origin, $e->getMessage()), 0, $e);
        }
    }

    /**
     * Operations the API serves without a token although the Swagger files do not say so
     * (spec/behavior.json): today only the login.
     *
     * @param array<array-key, mixed> $behavior
     *
     * @return list<string> "METHOD /path"
     */
    private static function publicOperations(array $behavior): array
    {
        $authentication = Json::object($behavior['authentication'] ?? null, 'behavior authentication');
        $login = Json::object($authentication['login'] ?? null, 'behavior authentication.login');

        return [Json::string($login['operation'] ?? null, 'behavior authentication.login.operation')];
    }

    /**
     * @param array<array-key, mixed> $spec
     *
     * @return array{array<string, string>, array<string, list<string>>} tag => group, and group => tags in order
     */
    private static function groups(array $spec): array
    {
        $groupOf = [];
        $tags = [];
        foreach (Json::list($spec['x-tagGroups'] ?? null, 'x-tagGroups') as $group) {
            $group = Json::object($group, 'x-tagGroups entry');
            $name = Json::string($group['name'] ?? null, 'x-tagGroups name');
            foreach (Json::list($group['tags'] ?? null, "x-tagGroups $name tags") as $tag) {
                $tag = Json::string($tag, "x-tagGroups $name tag");
                if (isset($groupOf[$tag])) {
                    throw new SpecException(sprintf('The tag "%s" is in the groups "%s" and "%s"', $tag, $groupOf[$tag], $name));
                }
                $groupOf[$tag] = $name;
                $tags[$name][] = $tag;
            }
        }

        return [$groupOf, $tags];
    }

    /**
     * @param array<array-key, mixed> $operation
     * @param array<string, string>   $groupOf
     * @param list<string>            $public
     * @param array<string, string>   $classes
     * @param array<array-key, mixed> $definitions
     *
     * @return array{id: string, method: string, path: string, group: string, name: string, auth: bool, experimental: bool, summary: string, description: string, parameters: list<OperationParameter>, signature: list<OperationParameter>, data: string, list: bool}
     */
    private static function operation(string $method, string $path, array $operation, array $groupOf, array $public, array $classes, array $definitions): array
    {
        $id = Json::string($operation['operationId'] ?? null, strtoupper($method) . " $path operationId");
        $group = null;
        foreach (Json::list($operation['tags'] ?? null, "$id tags") as $tag) {
            $tag = Json::string($tag, "$id tag");
            $tagGroup = $groupOf[$tag] ?? throw new SpecException(sprintf('%s: the tag "%s" is in no x-tagGroups group', $id, $tag));
            if ($group !== null && $group !== $tagGroup) {
                throw new SpecException(sprintf('%s: its tags are in the groups "%s" and "%s"', $id, $group, $tagGroup));
            }
            $group = $tagGroup;
        }
        if ($group === null) {
            throw new SpecException($id . ': an operation needs a tag');
        }

        $parameters = [];
        foreach (Json::list($operation['parameters'] ?? [], "$id parameters") as $parameter) {
            $parameters[] = OperationParameter::fromSpec(Json::object($parameter, "$id parameter"), $classes, $definitions, $id);
        }
        $variables = NameMap::properties($id, array_map(static fn (OperationParameter $p): string => $p->name, $parameters));
        $parameters = array_map(static fn (OperationParameter $p): OperationParameter => $p->withVariable($variables[$p->name]), $parameters);

        preg_match_all('/\{([^}]+)\}/', $path, $placeholders);
        $pathParameters = [];
        foreach ($placeholders[1] as $placeholder) {
            $found = array_values(array_filter($parameters, static fn (OperationParameter $p): bool => $p->in === 'path' && $p->name === $placeholder));
            $pathParameters[] = $found[0] ?? throw new SpecException(sprintf('%s: {%s} in %s has no path parameter', $id, $placeholder, $path));
        }
        foreach ($parameters as $parameter) {
            if ($parameter->in === 'path' && !in_array($parameter->name, $placeholders[1], true)) {
                throw new SpecException(sprintf('%s: path parameter "%s" does not appear in %s', $id, $parameter->name, $path));
            }
        }
        $required = array_values(array_filter($parameters, static fn (OperationParameter $p): bool => $p->in !== 'path' && $p->required));
        $optional = array_values(array_filter($parameters, static fn (OperationParameter $p): bool => !$p->required));
        usort($required, static fn (OperationParameter $a, OperationParameter $b): int => ($a->in === 'body' ? 0 : 1) <=> ($b->in === 'body' ? 0 : 1));
        usort($optional, static fn (OperationParameter $a, OperationParameter $b): int => ($a->in === 'body' ? 0 : 1) <=> ($b->in === 'body' ? 0 : 1));

        [$data, $list] = self::data($id, $operation, $classes, $definitions);
        $security = $operation['security'] ?? null;

        return [
            'id' => $id,
            'method' => strtoupper($method),
            'path' => $path,
            'group' => $group,
            'name' => self::methodName($id),
            'auth' => $security !== [] && !in_array(strtoupper($method) . ' ' . $path, $public, true),
            'experimental' => ($operation['x-experimental'] ?? false) === true,
            'summary' => is_string($operation['summary'] ?? null) ? $operation['summary'] : '',
            'description' => is_string($operation['description'] ?? null) ? $operation['description'] : '',
            'parameters' => $parameters,
            'signature' => [...$pathParameters, ...$required, ...$optional],
            'data' => $data,
            'list' => $list,
        ];
    }

    /**
     * The model the success envelope's `data` holds, and whether it is a list of them.
     *
     * @param array<array-key, mixed> $operation
     * @param array<string, string>   $classes
     * @param array<array-key, mixed> $definitions
     *
     * @return array{string, bool}
     */
    private static function data(string $id, array $operation, array $classes, array $definitions): array
    {
        $responses = Json::object($operation['responses'] ?? null, "$id responses");
        $success = Json::object($responses['200'] ?? null, "$id 200 response");
        $envelope = ModelSet::refName(Json::object($success['schema'] ?? null, "$id 200 schema")['$ref'] ?? null);
        $fields = Json::object(Json::object($definitions[$envelope] ?? null, $envelope)['properties'] ?? [], "$envelope properties");
        $data = is_array($fields['data'] ?? null) ? $fields['data'] : [];
        $list = ($data['type'] ?? null) === 'array';
        $target = $list ? (is_array($data['items'] ?? null) ? $data['items'] : []) : $data;
        $definition = isset($target['$ref']) ? ModelSet::refName($target['$ref']) : null;
        $class = $definition === null ? null : ($classes[$definition] ?? null);
        if ($definition === null || $class === null || (Json::object($definitions[$definition] ?? null, $definition)['type'] ?? null) !== 'object') {
            throw new SpecException($id . ': data is neither a $ref to a model nor a list of them');
        }

        return [$class, $list];
    }

    /**
     * @param list<string>                                                                                                                   $tags
     * @param list<array{id: string, method: string, path: string, group: string, name: string, auth: bool, experimental: bool, summary: string, description: string, parameters: list<OperationParameter>, signature: list<OperationParameter>, data: string, list: bool}> $operations
     */
    private static function service(string $group, string $class, array $tags, array $operations, ?string $portal): string
    {
        $owners = [];
        $used = [];
        foreach ($operations as $operation) {
            if (isset($owners[strtolower($operation['name'])])) {
                throw new SpecException(sprintf(
                    '%s and %s: %s::%s() would implement both',
                    $owners[strtolower($operation['name'])],
                    $operation['id'],
                    $class,
                    $operation['name'],
                ));
            }
            $owners[strtolower($operation['name'])] = $operation['id'];
            $used[] = $operation['data'];
            foreach ($operation['signature'] as $parameter) {
                if ($parameter->bodyClass !== null) {
                    $used[] = $parameter->bodyClass;
                }
            }
        }
        [$imports, $reference] = self::imports([...self::ALWAYS_IMPORTED, ...$used], $class);

        $lines = [
            '<?php',
            '',
            'declare(strict_types=1);',
            '',
            'namespace ' . self::NAMESPACE . ';',
            '',
            ...$imports,
            '',
            '/**',
            sprintf(' * %s: the operations tagged %s.', $group, implode(', ', $tags)),
            ' *',
            ' * Each method sends one operation and returns the envelope with `data` read into the',
            ' * model the spec declares. A code other than 0 is thrown as an ApiException.',
            ' *',
            self::GENERATED,
            ' */',
            sprintf('final class %s extends %s', $class, $reference(self::BASE_CLASS)),
            '{',
        ];
        foreach ($operations as $i => $operation) {
            if ($i > 0) {
                $lines[] = '';
            }
            array_push($lines, ...self::method($operation, $reference, $portal));
        }
        $lines[] = '}';

        return implode("\n", $lines) . "\n";
    }

    /**
     * @param array{id: string, method: string, path: string, group: string, name: string, auth: bool, experimental: bool, summary: string, description: string, parameters: list<OperationParameter>, signature: list<OperationParameter>, data: string, list: bool} $operation
     * @param callable(string): string                                                                                                                                                                                                  $reference
     *
     * @return list<string>
     */
    private static function method(array $operation, callable $reference, ?string $portal): array
    {
        $summary = trim($operation['summary']) === '' ? $operation['id'] : $operation['summary'];
        $doc = ['    /**'];
        foreach (DocText::lines($summary) as $line) {
            $doc[] = rtrim('     * ' . $line);
        }
        $description = trim($operation['description']);
        if ($description !== '' && $description !== trim($summary)) {
            $doc[] = '     *';
            foreach (DocText::lines($description) as $line) {
                $doc[] = rtrim('     * ' . $line);
            }
        }
        if ($operation['signature'] !== []) {
            $doc[] = '     *';
            foreach ($operation['signature'] as $parameter) {
                $doc[] = rtrim(sprintf('     * @param %s $%s %s', $parameter->docType($reference), $parameter->variable, $parameter->doc()));
            }
        }
        $data = $reference($operation['data']);
        $doc[] = '     *';
        $doc[] = sprintf('     * @return %s<%s>', $reference('Ashio\OpenProvider\Response\ApiResponse'), $operation['list'] ? "list<$data>" : $data);
        $doc[] = '     *';
        $doc[] = sprintf('     * @throws %s when the API refuses the call or cannot be reached', $reference('Ashio\OpenProvider\Exception\OpenProviderException'));
        if ($operation['experimental']) {
            $doc[] = '     *';
            $doc[] = '     * ' . DocText::experimental($portal);
        }
        $doc[] = '     */';

        $parameters = array_map(
            static fn (OperationParameter $p): string => sprintf('%s $%s%s', $p->phpType($reference), $p->variable, $p->required ? '' : ' = null'),
            $operation['signature'],
        );
        $return = $reference('Ashio\OpenProvider\Response\ApiResponse');
        $single = sprintf('    public function %s(%s): %s', $operation['name'], implode(', ', $parameters), $return);
        $signature = strlen($single) <= self::MAX_LINE
            ? [$single, '    {']
            : [
                sprintf('    public function %s(', $operation['name']),
                ...array_map(static fn (string $p): string => "        $p,", $parameters),
                "    ): $return {",
            ];

        $arguments = $operation['signature'] === []
            ? '[]'
            : "[\n" . implode('', array_map(
                static fn (OperationParameter $p): string => sprintf("            %s => \$%s,\n", var_export($p->name, true), $p->variable),
                $operation['signature'],
            )) . '        ]';

        return [
            ...$doc,
            sprintf('    #[%s(%s, %s, %s)]', $reference('Ashio\OpenProvider\Spec\Operation'), var_export($operation['method'], true), var_export($operation['path'], true), var_export($operation['id'], true)),
            ...$signature,
            sprintf(
                '        return self::%s($this->call(%s, %s), %s::class);',
                $operation['list'] ? 'objects' : 'object',
                var_export($operation['id'], true),
                $arguments,
                $data,
            ),
            '    }',
        ];
    }

    /**
     * @param list<array{id: string, method: string, path: string, group: string, name: string, auth: bool, experimental: bool, summary: string, description: string, parameters: list<OperationParameter>, signature: list<OperationParameter>, data: string, list: bool}> $operations
     */
    private static function registry(array $operations): string
    {
        $lines = [
            '<?php',
            '',
            'declare(strict_types=1);',
            '',
            'namespace ' . self::NAMESPACE . ';',
            '',
            'use Ashio\OpenProvider\Exception\InvalidArgumentException;',
            'use Ashio\OpenProvider\Spec\OperationSpec;',
            'use Ashio\OpenProvider\Spec\ParameterLocation;',
            'use Ashio\OpenProvider\Spec\ParameterSpec;',
            '',
            '/**',
            ' * The operations the services implement, as the request encoder reads them: method, path,',
            ' * each parameter\'s name, location and type, and whether the call needs a token.',
            ' *',
            self::GENERATED,
            ' */',
            'final class Operations',
            '{',
            '    /**',
            '     * The operationIds, in spec order.',
            '     *',
            '     * @var list<string>',
            '     */',
            '    public const IDS = [',
        ];
        foreach ($operations as $operation) {
            $lines[] = '        ' . var_export($operation['id'], true) . ',';
        }
        array_push(
            $lines,
            '    ];',
            '',
            '    /** @var array<string, OperationSpec> */',
            '    private static array $specs = [];',
            '',
            '    /**',
            '     * @throws InvalidArgumentException for an operationId no service implements',
            '     */',
            '    public static function get(string $operationId): OperationSpec',
            '    {',
            '        return self::$specs[$operationId] ??= self::build($operationId);',
            '    }',
            '',
            '    private static function build(string $operationId): OperationSpec',
            '    {',
            '        return match ($operationId) {',
        );
        foreach ($operations as $operation) {
            $head = sprintf(
                '            %s => new OperationSpec(%s, %s, %s, ',
                var_export($operation['id'], true),
                var_export($operation['method'], true),
                var_export($operation['path'], true),
                var_export($operation['id'], true),
            );
            $close = $operation['auth'] ? '),' : ', requiresAuth: false),';
            if ($operation['parameters'] === []) {
                $lines[] = $head . '[]' . $close;

                continue;
            }
            $lines[] = $head . '[';
            foreach ($operation['parameters'] as $parameter) {
                $lines[] = '                ' . $parameter->registryEntry() . ',';
            }
            $lines[] = '            ]' . $close;
        }
        array_push(
            $lines,
            '            default => throw new InvalidArgumentException(sprintf(\'No service implements the operation "%s"\', $operationId)),',
            '        };',
            '    }',
            '}',
        );

        return implode("\n", $lines) . "\n";
    }

    /**
     * @param array<string, string>       $services group => class
     * @param array<string, list<string>> $groupTags
     */
    private static function facade(array $services, array $groupTags): string
    {
        $imports = ['use Ashio\OpenProvider\Client\ApiClient;'];
        foreach ($services as $class) {
            $imports[] = 'use ' . self::NAMESPACE . '\\' . $class . ';';
        }
        sort($imports, SORT_STRING);
        $lines = [
            '<?php',
            '',
            'declare(strict_types=1);',
            '',
            'namespace Ashio\OpenProvider;',
            '',
            ...$imports,
            '',
            '/**',
            ' * The entry point: one accessor per service, each holding the operations of one tag group',
            ' * of the API. Nothing is sent until an operation is called.',
            ' *',
            ' *     $openProvider = new OpenProvider(ApiClient::create($config, $credentials));',
            ' *     $response = $openProvider->dns()->getZone(\'example.com\'); // ApiResponse<…>, ->data is the model',
            ' *',
            self::GENERATED,
            ' */',
            'final class OpenProvider',
            '{',
        ];
        foreach ($services as $class) {
            $lines[] = sprintf('    private ?%s $%s = null;', $class, self::accessor($class));
        }
        array_push(
            $lines,
            '',
            '    public function __construct(private readonly ApiClient $client)',
            '    {',
            '    }',
            '',
            '    public function client(): ApiClient',
            '    {',
            '        return $this->client;',
            '    }',
        );
        foreach ($services as $group => $class) {
            $accessor = self::accessor($class);
            array_push(
                $lines,
                '',
                '    /**',
                sprintf('     * %s: the operations tagged %s.', $group, implode(', ', $groupTags[$group])),
                '     */',
                sprintf('    public function %s(): %s', $accessor, $class),
                '    {',
                sprintf('        return $this->%s ??= new %s($this->client);', $accessor, $class),
                '    }',
            );
        }
        $lines[] = '}';

        return implode("\n", $lines) . "\n";
    }

    private static function accessor(string $class): string
    {
        return lcfirst(substr($class, 0, -strlen('Service')));
    }

    /**
     * The `use` lines of a service and how each class is written: by its short name, or fully
     * qualified when two classes share a short name or one shares the service's own name.
     *
     * @param list<string> $classes
     *
     * @return array{list<string>, \Closure(string): string}
     */
    private static function imports(array $classes, string $self): array
    {
        $classes = array_values(array_unique($classes));
        $byShort = [];
        foreach ($classes as $class) {
            $byShort[strtolower(self::short($class))][] = $class;
        }
        $imported = [];
        foreach ($classes as $class) {
            $short = strtolower(self::short($class));
            if (count($byShort[$short]) === 1 && $short !== strtolower($self)) {
                $imported[$class] = true;
            }
        }
        $lines = array_map(static fn (string $class): string => "use $class;", array_keys($imported));
        usort($lines, static fn (string $a, string $b): int => strcasecmp($a, $b));
        $reference = static fn (string $class): string => isset($imported[$class]) ? self::short($class) : '\\' . $class;

        return [$lines, $reference];
    }

    private static function short(string $class): string
    {
        $at = strrpos($class, '\\');

        return $at === false ? $class : substr($class, $at + 1);
    }
}
