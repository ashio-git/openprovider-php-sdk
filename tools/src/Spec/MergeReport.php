<?php

declare(strict_types=1);

namespace Ashio\OpenProvider\Tools\Spec;

/**
 * Renders spec/conflicts.md: what the merge decided, so a reviewer sees every non-trivial
 * choice without reading the merged spec.
 */
final class MergeReport
{
    public static function render(MergeResult $result, SourceManifest $manifest, string $mergedSha256): string
    {
        $conflicts = $result->conflicts();
        $unresolved = count($result->unresolvedConflicts());
        $portalOnly = $result->portalOnlyOperations();

        $lines = [
            '# Spec merge report',
            '',
            'Generated by `tools/spec-merge`. Do not edit: change `spec/overrides.json` and run the merge again.',
            'Policy: [docs/plans/2026-11-09-sdk-api-v1.md §4](../docs/plans/2026-11-09-sdk-api-v1.md).',
            '',
            '## Inputs',
            '',
            sprintf(
                '- `%s` at commit `%s`: %d files under `%s/`.',
                $manifest->repository,
                $manifest->commit,
                count($manifest->services),
                $manifest->directory,
            ),
            sprintf('- Developer portal bundle `%s`.', $manifest->portalUrl),
            '- Hashes: `spec/SHA256SUMS`. Retrieval details: `spec/PROVENANCE.md`.',
            '',
            '## Result',
            '',
            sprintf(
                '- Operations: %d (%d from the service files, %d only on the portal).',
                $result->operationCount(),
                $result->operationCount() - count($portalOnly),
                count($portalOnly),
            ),
            sprintf('- Definitions: %d, all reachable from the operations.', $result->definitionCount()),
            sprintf('- Conflicts: %d (%d unresolved).', count($conflicts), $unresolved),
            sprintf('- `spec/openprovider.json` sha256: `%s`.', $unresolved === 0 ? $mergedSha256 : 'not written'),
            '',
            '## Conflicts',
            '',
        ];

        if ($conflicts === []) {
            $lines[] = 'None.';
        } else {
            $lines[] = '| Id | Difference | Resolution | Reason |';
            $lines[] = '|---|---|---|---|';
            foreach ($conflicts as $conflict) {
                $lines[] = sprintf(
                    '| `%s` | %s | %s | %s |',
                    $conflict->id,
                    self::cell($conflict->detail),
                    $conflict->resolution === null ? '**unresolved**' : self::cell($conflict->resolution->use),
                    $conflict->resolution === null ? '' : self::cell($conflict->resolution->reason),
                );
            }
        }

        array_push(
            $lines,
            '',
            '## Operations only on the portal (marked `x-experimental`)',
            '',
            ...self::bullets($portalOnly),
        );
        array_push(
            $lines,
            '',
            '## Service operations outside the portal (dropped)',
            '',
            ...self::bullets($result->serviceOnlyOperations()),
        );
        array_push(
            $lines,
            '',
            '## Fields, parameters and responses only the portal has (added by union)',
            '',
            ...self::bullets($result->additions()),
        );
        array_push($lines, '', '## Enums whose values were united', '', ...self::bullets($result->enumUnions()));

        return implode("\n", $lines) . "\n";
    }

    /**
     * @param list<string> $items
     *
     * @return list<string>
     */
    private static function bullets(array $items): array
    {
        return $items === [] ? ['None.'] : array_map(static fn (string $item): string => '- `' . $item . '`', $items);
    }

    private static function cell(string $text): string
    {
        return str_replace(['|', "\n"], ['\\|', ' '], $text);
    }
}
